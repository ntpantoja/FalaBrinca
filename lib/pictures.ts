export function sequencePictures(words: string[]): Choice[] {
  return words
    .filter((word) => !["O", "A", "DE", "NA", "NO"].includes(word))
    .map((name, index) => ({
      name: `${index}:${name}`,
      emoji: pictures[name] || "✨",
    }));
}
